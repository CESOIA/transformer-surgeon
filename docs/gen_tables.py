"""Generate the documentation tables of the two dictionaries that drive the export.

    python docs/gen_tables.py            # rewrite docs/generated/*.md
    python docs/gen_tables.py --check    # exit 1 if the files are out of date

The tables are rendered from ``blocks/catalog.py::BLOCK_CATALOG`` and
``export/operations.py::BACKEND_OPERATIONS`` so the site never drifts from the
code; ``test/docs/test_generated_tables.py`` runs the check.
"""
import argparse
import sys
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent / "generated"


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def block_catalog_table() -> str:
    from transformersurgeon.blocks import BLOCK_CATALOG

    lines = ["| Family | Atom | Implements | Selected by | Object | Summary |", "|---|---|---|---|---|---|"]
    for family, atoms in BLOCK_CATALOG.items():
        for name, atom in atoms.items():
            lines.append(f"| `{family}` | `{name}` | `{atom['implements']}` | {atom['selected_by']} "
                         f"| `blocks.{atom['object']}` | {_cell(atom['summary'])} |")
    return "\n".join(lines) + "\n"


def _how(spec):
    if "convert_option" in spec:
        return f"convert option `{spec['convert_option']}`"
    if "config_field" in spec:
        return "config field " + ", ".join(f"`{b}.{f}`" for b, f in spec["config_field"].items())
    key = spec.get("model_key")
    return f"model dictionary `{key}`" if key else "single implementation"


def _value(value):
    return "—" if value is None else f"`{value}`"


def backend_operations_tables() -> str:
    from transformersurgeon.export import BACKEND_OPERATIONS, BACKENDS

    summary = ["| Block type | Chosen by | " + " | ".join(BACKENDS) + " |",
               "|---|---|" + "---|" * len(BACKENDS)]
    details = []
    for block_type, spec in BACKEND_OPERATIONS.items():
        defaults = [_value(spec["backends"][b]["default"]) for b in BACKENDS]
        summary.append(f"| `{block_type}` | {_how(spec)} | " + " | ".join(defaults) + " |")
        details += [f"### `{block_type}`", "", _cell(spec["description"]) + f" Chosen by: {_how(spec)}.", "",
                    "| Backend | Option | Device operation |", "|---|---|---|"]
        for backend in BACKENDS:
            entry = spec["backends"][backend]
            for option, text in entry["options"].items():
                mark = " (default)" if option == entry["default"] else ""
                details.append(f"| {backend} | `{option}`{mark} | {_cell(text)} |")
        details.append("")
    return ("Defaults per backend (— = chosen by the model dictionary):\n\n" + "\n".join(summary)
            + "\n\n" + "\n".join(details))


TABLES = {
    "block_catalog.md": block_catalog_table,
    "backend_operations.md": backend_operations_tables,
}

HEADER = "<!-- Generated by docs/gen_tables.py from the code; do not edit by hand. -->\n\n"


def render() -> dict:
    return {name: HEADER + fn() for name, fn in TABLES.items()}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    args = parser.parse_args(argv)
    stale = []
    for name, text in render().items():
        path = OUT_DIR / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(name)
        else:
            OUT_DIR.mkdir(exist_ok=True)
            path.write_text(text)
    if stale:
        print("Out of date (run python docs/gen_tables.py):", ", ".join(stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
